; tests/graster_probe.s - HUNK test executable (TEST ASSET, NOT ROM code).
; Black-box probe "graphics.library SetRast, RectFill, ScrollRaster, SetAPen/SetBPen/SetDrMd"
; (docs/analysis/graphics-raster-v34.md §9). Run from the startup-sequence of a floppy (tests/graster_probe.sh).
; Results go to a memory buffer whose bounds are printed on the direct serial port (SERDAT) before "GRP fin"; the
; harness reads it through gdb (the emulated serial link lost characters under load) and tests/graster_check.py
; compares it with the expected values. The probe then waits forever so that the buffer stays valid.
; The case tables come from graster_check.py (include "graster_cases.i", generated by the .sh).
; Test BitMap: 64 x 16, 2 planes (BytesPerRow 8, 128 bytes per plane) in CHIP between two 1024-byte guards.
; Layer tests: 64 x 32 x 2 screen BitMap. Header: "cp=x,y fl= 1e= 1f= fg= bg= md= mk= ao= mt=<8 bytes>" (hex).
; Dumps: "<row> <plane0 8 bytes> <plane1 8 bytes>" (hex).
; Assembly: vasmm68k_mot -Fhunkexe -kick1hunks -nosym -m68000 -I <dir of graster_cases.i> tests/graster_probe.s
; Authored code; public structures (graphics/rastport.h, gfx.h, clip.h, regions.h, layers.h).

SERDAT   EQU $DFF030
SERDATR  EQU $DFF018
SERPER   EQU $DFF032
O_G0     EQU 0           ; guard before plane 0 (1024 bytes)
O_PL0    EQU 1024        ; plane 0 (128 bytes)
O_PL1    EQU 1152        ; plane 1 (128 bytes)
O_G1     EQU 1280        ; guard after plane 1 (1024 bytes)
O_PAT    EQU 2304        ; area patterns (64 bytes)
O_SCR    EQU 2368        ; layer screen: 64 x 32 x 2 (512 bytes)
O_BIG    EQU 2880        ; 1280 x 2 x 1 (320 bytes) or 16 x 1100 x 1 (2200 bytes)
O_SM     EQU 5080        ; 16-byte guard, 20 x 3 x 1 plane (12 bytes), 16-byte guard
O_ROW    EQU 5124        ; copy of one 1280-pixel row (160 bytes)
CHIPSZ   EQU 5284
OBUFSZ   EQU 196608      ; output buffer (any memory)
PLSZ     EQU 128

; graphics LVOs checked against AROS rom/graphics/graphics.conf (bias 30, 6 bytes per slot)
LVO_InitRastPort EQU -198
LVO_WaitBlit     EQU -228
LVO_SetRast      EQU -234
LVO_Move         EQU -240
LVO_RectFill     EQU -306
LVO_SetAPen      EQU -342
LVO_SetBPen      EQU -348
LVO_SetDrMd      EQU -354
LVO_InitBitMap   EQU -390
LVO_ScrollRaster EQU -396
; layers LVOs checked against AROS rom/hyperlayers/layers.conf
LVO_CreateUpfrontLayer EQU -36
LVO_DeleteLayer        EQU -90
LVO_NewLayerInfo       EQU -144
LVO_DisposeLayerInfo   EQU -150

; RastPort (rastport.h)
RP_BM    EQU $04
RP_PTRN  EQU $08         ; AreaPtrn
RP_MASK  EQU $18
RP_FG    EQU $19
RP_BG    EQU $1A
RP_AOL   EQU $1B
RP_MODE  EQU $1C
RP_PTSZ  EQU $1D
RP_LPC   EQU $1E
RP_PC    EQU $1F
RP_FLAGS EQU $20
RP_LPTRN EQU $22
RP_CPX   EQU $24
RP_CPY   EQU $26
RP_MINT  EQU $28
BM_BPR   EQU 0           ; BitMap (gfx.h)
BM_DEPTH EQU 5
BM_PL    EQU 8
LR_RP    EQU $0C         ; Layer.rp (clip.h)
LR_FLAGS EQU $1E
LR_DMG   EQU $9C         ; Layer.DamageList
SMART    EQU 2
SIMPLE   EQU 1
END      EQU $7FFF       ; end of the layer case tables

CALL            macro
                move.l  rpa-vars(a4),a1
                jsr     \1(a6)
                endm
SETP            macro                ; SETP lvo,value
                move.l  #\2,d0
                CALL    \1
                endm
MSG             macro
                lea     \1(pc),a0
                bsr     puts
                endm

                section code,code
_start:
                movem.l d2-d7/a2-a6,-(sp)
                lea     vars(pc),a4
                move.w  #372,SERPER
                move.l  4.w,a6
                lea     gfxname(pc),a1
                moveq   #0,d0
                jsr     -552(a6)
                move.l  d0,gfxb-vars(a4)
                beq     .out
                lea     layname(pc),a1
                moveq   #0,d0
                jsr     -552(a6)
                move.l  d0,layb-vars(a4)
                beq     .closeg
                move.l  #CHIPSZ,d0
                move.l  #$10003,d1
                jsr     -198(a6)
                move.l  d0,chip-vars(a4)
                beq     .closel
                move.l  d0,a5
                move.l  #OBUFSZ,d0
                move.l  #$10001,d1
                jsr     -198(a6)
                move.l  d0,obuf-vars(a4)
                move.l  d0,optr-vars(a4)
                beq     .closel
                MSG     m_start
                move.l  gfxb-vars(a4),a6
                lea     patterns(pc),a0      ; patterns into chip memory (the 1.3 blitter reads them)
                lea     O_PAT(a5),a1
                moveq   #PATSZ/2-1,d0
.cp:            move.w  (a0)+,(a1)+
                dbra    d0,.cp
                lea     bm-vars(a4),a0
                moveq   #2,d0
                moveq   #64,d1
                moveq   #16,d2
                jsr     LVO_InitBitMap(a6)
                lea     O_PL0(a5),a0
                move.l  a0,bm+8-vars(a4)
                lea     O_PL1(a5),a0
                move.l  a0,bm+12-vars(a4)
                lea     bms-vars(a4),a0
                moveq   #2,d0
                moveq   #64,d1
                moveq   #32,d2
                jsr     LVO_InitBitMap(a6)
                lea     O_SCR(a5),a0
                move.l  a0,bms+8-vars(a4)
                lea     O_SCR+256(a5),a0
                move.l  a0,bms+12-vars(a4)

                bsr     t_r0
                bsr     t_r1
                bsr     t_cases
                bsr     t_r8x
                bsr     t_layers
                bsr     t_sizes

                MSG     m_end
                moveq   #1,d3                ; "GRP buf=<start> end=<end>" twice, then "GRP fin", on the serial port
.sb:            lea     m_buf(pc),a0
                bsr     sputs
                move.l  obuf-vars(a4),d0
                bsr     shex8
                lea     m_bend(pc),a0
                bsr     sputs
                move.l  optr-vars(a4),d0
                bsr     shex8
                moveq   #10,d1
                bsr     sputc
                dbra    d3,.sb
                lea     m_end(pc),a0
                bsr     sputs
                move.l  4.w,a6               ; the buffer must stay valid until the harness has read it
                moveq   #0,d0
                jsr     -318(a6)             ; Wait(0): never returns
.closel:        move.l  4.w,a6
                move.l  layb-vars(a4),a1
                jsr     -414(a6)
.closeg:        move.l  4.w,a6
                move.l  gfxb-vars(a4),a1
                jsr     -414(a6)
.out:           movem.l (sp)+,d2-d7/a2-a6
                moveq   #0,d0
                rts

; --- R0: registers changed by the six functions (markers in d0-d7/a0/a2-a5; low words = arguments)
t_r0:           bsr     fresh
                lea     r0tab(pc),a3
.l:             move.w  (a3)+,d0
                beq.s   .e
                lea     mk-vars(a4),a0
                moveq   #5,d1
.m:             move.l  (a3)+,(a0)+
                dbra    d1,.m
                MSG     m_r0
                move.l  a3,a0
                bsr     puts
                move.l  a0,d1                ; skip the name (even boundary)
                addq.l  #1,d1
                and.b   #$FE,d1
                move.l  d1,-(sp)
                bsr     regt
                move.l  (sp)+,a3
                bsr     fresh
                bra.s   .l
.e:             rts

; --- R1: setter sequence of graster_check.R1, header after each call
t_r1:           lea     r1tab(pc),a3
.l:             move.l  (a3)+,d2
                bmi.s   .e
                move.l  (a3)+,d3
                move.l  rpa-vars(a4),a0
                cmp.w   #4,d2
                bne.s   .n4
                move.w  d3,RP_FLAGS(a0)
                bra.s   .l
.n4:            cmp.w   #5,d2
                bne.s   .n5
                move.b  d3,RP_PC(a0)
                bra.s   .l
.n5:            cmp.w   #6,d2
                bne.s   .n6
                move.b  d3,RP_AOL(a0)
                bra.s   .l
.n6:            cmp.w   #7,d2
                bne.s   .n7
                move.b  d3,RP_LPC(a0)
                bra.s   .l
.n7:            tst.w   d2
                bne.s   .set
                bsr     fresh0
                bra.s   .pr
.set:           move.l  d3,d0
                move.l  rpa-vars(a4),a1
                cmp.w   #1,d2
                bne.s   .b
                jsr     LVO_SetAPen(a6)
                bra.s   .pr
.b:             cmp.w   #2,d2
                bne.s   .d
                jsr     LVO_SetBPen(a6)
                bra.s   .pr
.d:             jsr     LVO_SetDrMd(a6)
.pr:            MSG     m_r1
                bsr     hdr
                bra     .l
.e:             rts

; --- case table: background, RastPort state, one call, header + dump + guards
CS_ID    EQU 0
CS_BGT   EQU 2
CS_FG    EQU 4
CS_BGP   EQU 6
CS_MODE  EQU 8
CS_MASK  EQU 10
CS_PTSZ  EQU 12
CS_POFF  EQU 14
CS_AOL   EQU 16
CS_FLAGS EQU 18
CS_LPTRN EQU 20
CS_FN    EQU 22
CS_ARGS  EQU 24
CS_SIZE  EQU 36
t_cases:        lea     cases(pc),a3
.l:             tst.w   (a3)
                bmi     .e
                bsr     clrall
                lea     bm-vars(a4),a2
                moveq   #64,d4
                moveq   #16,d5
                moveq   #0,d6
                moveq   #0,d7
                move.w  CS_BGT(a3),d3
                bsr     bgdraw
                bsr     rpinit0
                move.w  CS_FG(a3),d0
                ext.l   d0
                CALL    LVO_SetAPen
                move.w  CS_BGP(a3),d0
                ext.l   d0
                CALL    LVO_SetBPen
                move.w  CS_MODE(a3),d0
                ext.l   d0
                CALL    LVO_SetDrMd
                moveq   #33,d0
                moveq   #7,d1
                CALL    LVO_Move
                move.l  rpa-vars(a4),a0
                move.b  CS_MASK+1(a3),RP_MASK(a0)
                move.b  CS_AOL+1(a3),RP_AOL(a0)
                move.w  CS_LPTRN(a3),RP_LPTRN(a0)
                move.w  CS_FLAGS(a3),d0
                or.w    d0,RP_FLAGS(a0)
                move.b  CS_PTSZ+1(a3),RP_PTSZ(a0)
                clr.l   RP_PTRN(a0)
                move.w  CS_POFF(a3),d0
                bmi.s   .np
                lea     O_PAT(a5),a1
                adda.w  d0,a1
                move.l  a1,RP_PTRN(a0)
.np:            movem.w CS_ARGS(a3),d0-d5
                ext.l   d0
                ext.l   d1
                ext.l   d2
                ext.l   d3
                ext.l   d4
                ext.l   d5
                move.l  rpa-vars(a4),a1
                move.w  CS_FN(a3),d6
                bne.s   .f1
                jsr     LVO_RectFill(a6)
                bra.s   .done
.f1:            cmp.w   #1,d6
                bne.s   .f2
                jsr     LVO_SetRast(a6)
                bra.s   .done
.f2:            jsr     LVO_ScrollRaster(a6)
.done:          jsr     LVO_WaitBlit(a6)
                moveq   #'T',d1
                bsr     putc
                move.w  CS_ID(a3),d0
                bsr     pdec
                bsr     sp1
                bsr     hdr
                lea     bm-vars(a4),a2
                moveq   #16,d7
                bsr     dump
                bsr     guards
                lea     CS_SIZE(a3),a3
                bra     .l
.e:             rts

; guards: "G" then " <offset from plane 0>=<byte>" for every non-zero guard byte
guards:         moveq   #'G',d1
                bsr     putc
                move.l  #O_G0,d7
.g:             cmp.l   #O_PL0,d7
                bne.s   .g1
                move.l  #O_G1,d7
.g1:            cmp.l   #O_G1+1024,d7
                beq.s   .ge
                tst.b   0(a5,d7.l)
                beq.s   .gn
                bsr     sp1
                move.w  d7,d0
                sub.w   #O_PL0,d0
                bsr     pdec
                moveq   #'=',d1
                bsr     putc
                move.b  0(a5,d7.l),d0
                bsr     phex2
.gn:            addq.l  #1,d7
                bra.s   .g
.ge:            bra     nl

; --- R8 extra: SetRast(1) on a 20 x 3 x 1 BitMap (BytesPerRow 4) between 16-byte guards
t_r8x:          lea     O_SM(a5),a0
                moveq   #43,d0
.c:             clr.b   (a0)+
                dbra    d0,.c
                lea     bm3-vars(a4),a0
                moveq   #1,d0
                moveq   #20,d1
                moveq   #3,d2
                jsr     LVO_InitBitMap(a6)
                lea     O_SM+16(a5),a0
                move.l  a0,bm3+8-vars(a4)
                bsr     rpinit0
                move.l  rpa-vars(a4),a1
                lea     bm3-vars(a4),a0
                move.l  a0,RP_BM(a1)
                moveq   #1,d0
                jsr     LVO_SetRast(a6)
                jsr     LVO_WaitBlit(a6)
                lea     O_SM+16(a5),a0
                moveq   #0,d2
                moveq   #11,d0
.n:             cmp.b   #$FF,(a0)+
                bne.s   .n1
                addq.w  #1,d2
.n1:            dbra    d0,.n
                lea     m_s20(pc),a0
                bsr     pcount
                moveq   #0,d2                ; non-zero guard bytes: offsets 0..15 and 28..43 of the block
                lea     O_SM(a5),a0
                bsr.s   .g16
                lea     O_SM+28(a5),a0
                bsr.s   .g16
                lea     m_g20(pc),a0
                bra     pcount
.g16:           moveq   #15,d0
.g:             tst.b   (a0)+
                beq.s   .gn
                addq.w  #1,d2
.gn:            dbra    d0,.g
                rts
; pcount(a0 = "S name", d2.w = count): "S name n=<count>"
pcount:         bsr     puts
                lea     m_n(pc),a0
                bsr     puts
                move.w  d2,d0
                bsr     pdecu0
                bra     nl

; --- R10 layers on the 64 x 32 x 2 screen BitMap
t_layers:       moveq   #0,d7                ; (a) RectFill then SetRast, SMART back under SIMPLE front
                bsr     la_one
                moveq   #1,d7
                bsr     la_one
                bsr     lb_phase
                lea     lctab(pc),a3         ; (c) ScrollRaster in a SMART layer alone
.c:             cmp.w   #END,(a3)
                beq.s   .ce
                bsr     lc_one
                lea     12(a3),a3
                bra.s   .c
.ce:            lea     ldtab(pc),a3         ; (d) SIMPLE layer under a front layer: damage
.d:             cmp.w   #END,(a3)
                beq.s   .de
                bsr     ld_one
                lea     22(a3),a3
                bra.s   .d
.de:            lea     letab(pc),a3         ; (e) existing damage
.ee:            cmp.w   #END,(a3)
                beq.s   .r
                bsr     le_one
                lea     12(a3),a3
                bra.s   .ee
.r:             rts

; la_one(d7 = 0 RectFill / 1 SetRast)
la_one:         bsr     clrscr
                bsr     newli
                beq     .r
                moveq   #5,d0
                moveq   #3,d1
                moveq   #50,d2
                moveq   #27,d3
                moveq   #SMART,d4
                bsr     newly
                move.l  d0,lyb-vars(a4)
                beq     .fail
                moveq   #30,d0
                moveq   #0,d1
                moveq   #63,d2
                moveq   #15,d3
                moveq   #SIMPLE,d4
                bsr     newly
                move.l  d0,lyf-vars(a4)
                beq     .fail1
                bsr     lyrp
                tst.w   d7
                bne.s   .sr
                SETP    LVO_SetAPen,3
                moveq   #-5,d0
                moveq   #-3,d1
                moveq   #60,d2
                moveq   #40,d3
                CALL    LVO_RectFill
                lea     m_larb(pc),a0
                bra.s   .p
.sr:            moveq   #2,d0
                CALL    LVO_SetRast
                lea     m_lasb(pc),a0
.p:             bsr     ldump
                move.l  lyf-vars(a4),a1
                bsr     dellay
                lea     m_lara(pc),a0
                tst.w   d7
                beq.s   .p2
                lea     m_lasa(pc),a0
.p2:            bsr     ldump
.fail1:         move.l  lyb-vars(a4),a1
                bsr     dellay
.fail:          bra     displi
.r:             rts

; lb_phase: pattern F000/0F00 JAM1 RectFill(0,0,20,3) in a SMART layer at (5,3), then the same with the right
; part behind a SMART front layer that is deleted before the dump
lb_phase:       moveq   #0,d7
.again:         bsr     clrscr
                bsr     newli
                beq     .r
                moveq   #5,d0
                moveq   #3,d1
                moveq   #50,d2
                moveq   #27,d3
                moveq   #SMART,d4
                bsr     newly
                move.l  d0,lyb-vars(a4)
                beq     .fail
                clr.l   lyf-vars(a4)
                tst.w   d7
                beq.s   .one
                moveq   #20,d0
                moveq   #0,d1
                moveq   #63,d2
                moveq   #15,d3
                moveq   #SMART,d4
                bsr     newly
                move.l  d0,lyf-vars(a4)
.one:           bsr     lyrp
                SETP    LVO_SetDrMd,0
                move.l  rpa-vars(a4),a0
                lea     O_PAT(a5),a1
                move.w  #PO_F000,d0
                adda.w  d0,a1
                move.l  a1,RP_PTRN(a0)
                move.b  #1,RP_PTSZ(a0)
                moveq   #0,d0
                moveq   #0,d1
                moveq   #20,d2
                moveq   #3,d3
                CALL    LVO_RectFill
                move.l  lyf-vars(a4),d0
                beq.s   .nf
                move.l  d0,a1
                bsr     dellay
.nf:            lea     m_lb(pc),a0
                tst.w   d7
                beq.s   .p
                lea     m_lbu(pc),a0
.p:             bsr     ldump
                move.l  lyb-vars(a4),a1
                bsr     dellay
.fail:          bsr     displi
                addq.w  #1,d7
                cmp.w   #2,d7
                blo     .again
.r:             rts

; lc_one(a3 = dx, dy, x0, y0, x1, y1): SMART layer (5,3)-(50,27) alone with content, APen 1, BPen 2, JAM2
lc_one:         bsr     clrscr
                bsr     newli
                beq     .r
                moveq   #5,d0
                moveq   #3,d1
                moveq   #50,d2
                moveq   #27,d3
                moveq   #SMART,d4
                bsr     newly
                move.l  d0,lyb-vars(a4)
                beq     .fail
                bsr     lcontent
                bsr     lyrp
                SETP    LVO_SetBPen,2
                bsr     lscroll
                lea     m_lc(pc),a0
                bsr     puts
                bsr     pargs
                bsr     nl
                bsr     ldump0
                move.l  lyb-vars(a4),a1
                bsr     dellay
.fail:          bra     displi
.r:             rts
; lscroll(a3 = 6 words): ScrollRaster on rpa
lscroll:        movem.w (a3),d0-d5
                ext.l   d0
                ext.l   d1
                ext.l   d2
                ext.l   d3
                ext.l   d4
                ext.l   d5
                CALL    LVO_ScrollRaster
                jmp     LVO_WaitBlit(a6)
; pargs: " args=dx,dy,x0,y0,x1,y1" from a3
pargs:          lea     m_args(pc),a0
                bsr     puts
                move.l  a3,a2
                moveq   #5,d2
.l:             move.w  (a2)+,d0
                bsr     pdec
                tst.w   d2
                beq.s   .e
                bsr     comma
.e:             dbra    d2,.l
                rts

; ld_one(a3 = 6 words of arguments, front x0,y0,x1,y1, front flags): SIMPLE back layer with content, front
; layer created after the content
ld_one:         bsr     clrscr
                bsr     newli
                beq     .r
                moveq   #5,d0
                moveq   #3,d1
                moveq   #50,d2
                moveq   #27,d3
                moveq   #SIMPLE,d4
                bsr     newly
                move.l  d0,lyb-vars(a4)
                beq     .fail
                bsr     lcontent
                movem.w 12(a3),d0-d4
                bsr     newly
                move.l  d0,lyf-vars(a4)
                beq     .fail1
                bsr     lyrp
                SETP    LVO_SetBPen,2
                bsr     lscroll
                lea     m_ld(pc),a0
                bsr     puts
                bsr     pargs
                lea     m_hid(pc),a0         ; hidden part in back-layer coordinates
                bsr     puts
                movem.w 12(a3),d2-d5
                cmp.w   #5,d2
                bge.s   .h0
                moveq   #5,d2
.h0:            cmp.w   #3,d3
                bge.s   .h1
                moveq   #3,d3
.h1:            cmp.w   #50,d4
                ble.s   .h2
                moveq   #50,d4
.h2:            cmp.w   #27,d5
                ble.s   .h3
                moveq   #27,d5
.h3:            move.w  d2,d0
                subq.w  #5,d0
                bsr     pdec
                bsr     comma
                move.w  d3,d0
                subq.w  #3,d0
                bsr     pdec
                bsr     comma
                move.w  d4,d0
                subq.w  #5,d0
                bsr     pdec
                bsr     comma
                move.w  d5,d0
                subq.w  #3,d0
                bsr     pdec
                bsr     pdamage
                bsr     ldump0
                move.l  lyf-vars(a4),a1
                bsr     dellay
.fail1:         move.l  lyb-vars(a4),a1
                bsr     dellay
.fail:          bra     displi
